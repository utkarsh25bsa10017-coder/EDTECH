//! Postgres (Supabase) connection and schema.
//!
//! Only this server talks to the database. Every table has row-level security
//! turned on with no policies, and Supabase's `anon` / `authenticated` roles
//! have no grants, so the public Supabase keys can't read or write anything.
//! The server connects as the table owner, which RLS doesn't restrict.

use sqlx::{
    postgres::{PgConnectOptions, PgPoolOptions, PgSslMode},
    PgPool,
};
use std::{str::FromStr, time::Duration};

const SCHEMA: &str = r#"
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    username TEXT UNIQUE,
    phone TEXT UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'admin')),
    created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    token TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
-- Passes are keyed by phone so a payment can arrive before the account exists.
CREATE TABLE IF NOT EXISTS passes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone TEXT NOT NULL,
    exam TEXT NOT NULL,
    tier TEXT NOT NULL,
    payment_id TEXT UNIQUE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS passes_phone ON passes(phone);
CREATE TABLE IF NOT EXISTS leads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone TEXT NOT NULL,
    name TEXT,
    exam TEXT NOT NULL,
    score BIGINT,
    total BIGINT,
    source TEXT NOT NULL,
    consent BOOLEAN NOT NULL DEFAULT false,
    opted_out BOOLEAN NOT NULL DEFAULT false,
    followup_step BIGINT NOT NULL DEFAULT 0,
    next_followup_at BIGINT,
    created_at BIGINT NOT NULL,
    UNIQUE (phone, exam)
);
CREATE TABLE IF NOT EXISTS attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    exam TEXT NOT NULL,
    paper TEXT NOT NULL,
    score DOUBLE PRECISION NOT NULL,
    total BIGINT NOT NULL,
    answers JSONB NOT NULL,
    topics JSONB NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS attempts_user ON attempts(user_id);
CREATE TABLE IF NOT EXISTS questions (
    id TEXT PRIMARY KEY,
    exam TEXT NOT NULL,
    subject TEXT NOT NULL,
    topic TEXT NOT NULL,
    difficulty TEXT NOT NULL,
    qtype TEXT NOT NULL,
    status TEXT NOT NULL,
    body JSONB NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS questions_exam_status ON questions(exam, status);
CREATE TABLE IF NOT EXISTS wa_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone TEXT NOT NULL,
    role TEXT NOT NULL,
    content TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS wa_messages_phone ON wa_messages(phone, id);

-- Lock the tables away from Supabase's public API roles.
DO $$
DECLARE
    t TEXT;
    r TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['users', 'sessions', 'passes', 'leads', 'attempts', 'questions', 'wa_messages'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
                EXECUTE format('REVOKE ALL ON TABLE %I FROM %I', t, r);
            END IF;
        END LOOP;
    END LOOP;
END $$;
"#;

fn transient(e: &sqlx::Error) -> bool {
    matches!(e, sqlx::Error::Io(_) | sqlx::Error::Tls(_) | sqlx::Error::PoolTimedOut)
}

/// Connects to `DATABASE_URL` and creates the tables. TLS is required unless
/// the URL sets its own `sslmode`. Network errors are retried every 10 seconds
/// (the retry rule in docs/ARCHITECTURE.md); a bad password or URL stops the server.
pub async fn connect(url: &str) -> Result<PgPool, sqlx::Error> {
    let mut opts = PgConnectOptions::from_str(url)?;
    if !url.contains("sslmode=") {
        opts = opts.ssl_mode(PgSslMode::Require);
    }
    let pool = PgPoolOptions::new()
        .max_connections(5)
        .acquire_timeout(Duration::from_secs(20))
        .connect_lazy_with(opts);
    let mut tries = 0u32;
    loop {
        match sqlx::raw_sql(SCHEMA).execute(&pool).await {
            Ok(_) => return Ok(pool),
            Err(e) if transient(&e) => {
                tries += 1;
                tracing::warn!("database unreachable ({e}), retrying in 10 s (try {tries})");
                tokio::time::sleep(Duration::from_secs(10)).await;
            }
            Err(e) => return Err(e),
        }
    }
}
